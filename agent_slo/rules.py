"""Render Prometheus recording and alerting rules for agent SLOs.

slo-toolkit's own ``to_prometheus_rules`` cannot filter the denominator by agent or add event
guards, so this module writes the rule file itself. Every window, burn-rate threshold, severity and
``for:`` value comes from slo-toolkit (via ``budget.build_windows``), the same source
``evaluate_budget`` uses; the alert summary text is written here (slo-toolkit's wording mentions an
environment and an availability SLI that do not exist in agent-slo).
Alerts read only the exact ``agent_slo_window_*`` gauges from ``metrics.py``. Every string scalar
is JSON-quoted, which is valid YAML.

Pure function, no shared state. Validate the output with ``promtool check rules``.
"""

from __future__ import annotations

import json
import re
from collections.abc import Mapping, Sequence

from agent_slo.budget import DEFAULT_WINDOWS, MIN_BAD_EVENTS, SLO_NAME, build_windows, window_label
from agent_slo.config import AgentConfig

EXPORT_STALE_SECONDS = 900
POLICY_HINT = "Error budget policy: freeze auto-merge for this agent and require human review."


def _q(value: str) -> str:
    return json.dumps(value)


def _num(value: float) -> str:
    # 12 significant digits: strips float noise (6.000000000000001) without distorting tiny values.
    return repr(float(f"{value:.12g}"))


def _alert_name(window_name: str) -> str:
    return "AgentSLO" + re.sub(r"[^A-Za-z0-9]", "", window_name)


def _record_name(label: str) -> str:
    return f"agent_slo:burn_rate:ratio_{label}"


def _rule(lines: list[str], kind: str, name: str, expr: str, **extra: object) -> None:
    lines += [f"      - {kind}: {_q(name)}", f"        expr: {_q(expr)}"]
    if "for_" in extra:
        lines.append(f"        for: {_q(str(extra['for_']))}")
    for section in ("labels", "annotations"):
        values = extra.get(section)
        if isinstance(values, dict):
            lines.append(f"        {section}:")
            lines += [f"          {k}: {_q(str(v))}" for k, v in values.items()]


def render_rules(
    configs: Mapping[str, AgentConfig],
    *,
    compliance_days: int = 30,
    windows: Sequence[tuple[str, float, float, float, str]] = DEFAULT_WINDOWS,
) -> str:
    """The full rule file (YAML text) for every configured agent plus the global export check."""
    lines = [
        "# Generated by agent-slo; thresholds from slo-toolkit. Review, then run:",
        "#   promtool check rules <this file>",
        "groups:",
    ]
    for agent, cfg in sorted(configs.items()):
        calc, alert_windows = build_windows(cfg, compliance_days, windows)
        sel = f"agent={_q(agent)}"

        def gauge(metric: str, hours: float, sel: str = sel) -> str:
            return f'{metric}{{{sel},window="{window_label(hours)}"}}'

        lines += [f"  - name: {_q('agent-slo.' + agent)}", "    rules:"]
        hours = sorted(
            {h for w in alert_windows for h in (w.short_window_hours, w.long_window_hours)}
        )
        for h in hours:
            expr = (
                f"(sum by (agent) ({gauge('agent_slo_window_bad', h)})"
                f" / sum by (agent) ({gauge('agent_slo_window_eligible', h)}))"
                f" / {_num(calc.error_budget)}"
            )
            _rule(lines, "record", _record_name(window_label(h)), expr, labels={"agent": agent})
        for w in alert_windows:
            short, long_ = w.short_window_hours, w.long_window_hours
            thr = _num(w.burn_rate)
            expr = (
                f"{_record_name(window_label(short))}{{{sel}}} > {thr}\n"
                f"and on(agent) {_record_name(window_label(long_))}{{{sel}}} > {thr}\n"
                f"and on(agent) {gauge('agent_slo_window_eligible', short)} >= {cfg.min_events}\n"
                f"and on(agent) {gauge('agent_slo_window_bad', short)} >= {MIN_BAD_EVENTS}"
            )
            _rule(
                lines,
                "alert",
                _alert_name(w.name),
                expr,
                for_=w.pending_for,
                labels={"severity": w.severity.value, "agent": agent, "slo": SLO_NAME},
                annotations={
                    "summary": (
                        f"{agent} pass-rate: burning {w.budget_fraction * 100:g}% of the "
                        f"{compliance_days}d error budget in {window_label(short)} "
                        f"(burn rate above {thr}x over both {window_label(short)} and "
                        f"{window_label(long_)})"
                    )
                },
            )
        _rule(
            lines,
            "alert",
            "AgentSLOBudgetExhausted",
            f"agent_slo_budget_exhausted{{{sel}}} == 1",
            for_="5m",
            labels={"severity": "page", "agent": agent, "slo": SLO_NAME},
            annotations={
                "summary": f"{agent} has exhausted its {compliance_days}d pass-rate error budget. "
                + POLICY_HINT
            },
        )
        _rule(
            lines,
            "alert",
            "AgentSLOGateBlockBreach",
            f"agent_slo_gate_block_breach{{{sel}}} == 1",
            for_="5m",
            labels={"severity": "ticket", "agent": agent, "slo": "gate-block-rate"},
            annotations={
                "summary": f"{agent} gate-block rate is above the "
                f"{cfg.gate_block_ceiling * 100:g}% ceiling over {compliance_days}d"
            },
        )
    lines += [f"  - name: {_q('agent-slo.export')}", "    rules:"]
    _rule(
        lines,
        "alert",
        "AgentSLOExportStale",
        f"time() - agent_slo_export_timestamp_seconds > {EXPORT_STALE_SECONDS}\n"
        "or absent(agent_slo_export_timestamp_seconds)",
        for_="5m",
        labels={"severity": "page"},
        annotations={
            "summary": "agent-slo metrics are missing or stale; burn-rate alerts cannot be trusted"
        },
    )
    return "\n".join(lines) + "\n"
